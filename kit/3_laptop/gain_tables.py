#!/usr/bin/env python3
"""gain_tables.py - level bytes into dsp_core gain words, and the ROM rtl/gain_rom.vh.

What the host did in MOST25-to-AUDIO (listener_fw/components/mostctl/sound.c, dsp_img.c), now
done by the FPGA: a level from the ring becomes the word amp_out's engine takes for a gain.

    python gain_tables.py        writes ../rtl/gain_rom.vh (two case functions, 256 entries each)

Words are Q4.28 (1.0 = 2^28). The engine glides each gain towards its target once a frame,
g = k*t + (1 - k)*g, and takes k*t as the word (dsp_asm.py, C_KT); k = 1/256 as the host had it
(K_GLIDE), 5.3 ms from silence to full at 48 kHz. So a table entry is round(k * gain * 2^28),
saturated like the host's q28().

Two tables:
  gain_db_word(db)    a SpeakerLevel byte, signed dB: 10^(dB/20); at or below -120 dB silence
                      (sound.c read those as SND_SILENT)
  gain_raw_word(raw)  a 0xF0.0x409 level byte, raw 0..255: the host's placeholder curve
                      snd_curve_db(raw, 40) = 40 log10(raw / 40) dB, i.e. amplitude (raw/40)^2,
                      0 = silence, 40 and above = full. RAW_MAX = 40 is a PLACEHOLDER: the real
                      curve comes from a recording of the car (volume shown against the byte).
"""
from __future__ import annotations

import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROM_VH = HERE.parent / "rtl" / "gain_rom.vh"

FRAC = 28
ONE = 1 << FRAC
K_GLIDE = 1.0 / 256.0
SILENT_DB = -120            # sound.c: a SpeakerLevel at or below this is silence
RAW_MAX = 40                # sound.c snd_cfg_default vol_max[SND_VOL_F0]: PLACEHOLDER
N_BQ = 8                    # dsp_asm.py: biquads on stream 0, 5 words each
N_STREAMS = 4
N_OUT = 2
C_IMAGE = 5 * N_BQ + N_STREAMS * N_OUT + 1       # 49 words a set: 0 .. C_1MK (the host's had 47, three streams)


def q28(x: float) -> int:
    """round(x * 2^28), saturated to a signed 32-bit word, for x >= 0 (dsp_img.c q28, lround)."""
    v = math.floor(x * ONE + 0.5)
    return min(v, 0x7FFFFFFF)


def gain_db(db: int) -> float:
    return 0.0 if db <= SILENT_DB else 10.0 ** (db / 20.0)


def gain_raw(raw: int) -> float:
    if raw <= 0:
        return 0.0
    if raw >= RAW_MAX:
        return 1.0
    return (raw / RAW_MAX) ** 2


def kt_word(gain: float) -> int:
    return q28(K_GLIDE * gain)


def db_word(db: int) -> int:
    """The gain word for a signed dB byte (-128..127)."""
    return kt_word(gain_db(db))


def raw_word(raw: int) -> int:
    """The gain word for a raw 0x409 level byte (0..255)."""
    return kt_word(gain_raw(raw))


W_ONE = q28(1.0)                        # 0x10000000: a straight biquad's b0
W_1MK = q28(1.0 - K_GLIDE)              # 0x0FF00000: C_1MK
assert W_ONE == 0x10000000 and W_1MK == 0x0FF00000
assert db_word(0) == 0x00100000 and raw_word(RAW_MAX) == 0x00100000
assert db_word(SILENT_DB) == 0 and raw_word(0) == 0

# The levels a stream plays at until the car has said anything about it (the user's decision of
# 2026-10-03: a start-up level of about a third of full volume or less, the announcement
# streams at levels of the user's own). Settings of the build: change them here.
# The sinks are JLR's as mObridge's MOST25 DA guide (pp. 18-19) gives them for Jaguar and Land
# Rover: sink 2 phone, navigation and voice, sink 3 the parking sensors, sink 4 the chimes.
DEFAULT_MAIN_DB = -12       # stream 0, the main source: a quarter of full amplitude
DEFAULT_S1_DB = -6          # stream 1 (sink 2: phone, navigation, voice)
DEFAULT_S2_DB = -6          # stream 2 (sink 3: parking sensors)
DEFAULT_S3_DB = -6          # stream 3 (sink 4: chimes): also its level for good, unless a SpeakerLevel
                            # names sink 4 - no volume message is on record for it, and a chime must
                            # not vanish with the volume turned down
DEFAULT_DB = (DEFAULT_MAIN_DB, DEFAULT_S1_DB, DEFAULT_S2_DB, DEFAULT_S3_DB)


def default_word(stream: int) -> int:
    """The gain word stream 0..3 starts with."""
    return db_word(DEFAULT_DB[stream])


def rom_text() -> str:
    lines = [
        "// gain_rom.vh - level byte -> gain word (k x gain, Q4.28, k = 1/256). GENERATED by",
        "// sim/gain_tables.py: do not edit. gain_db_word: a SpeakerLevel byte, signed dB, silence",
        f"// at or below {SILENT_DB} dB. gain_raw_word: a 0xF0.0x409 byte on the placeholder curve",
        f"// (raw / {RAW_MAX})^2, full from {RAW_MAX} up - to be replaced from a recording.",
        "// GAIN_DEF_*: what a stream plays at until the car has said anything about it.",
        f"localparam [31:0] GAIN_DEF_MAIN = 32'h{default_word(0):08X};   // {DEFAULT_MAIN_DB:+d} dB",
        f"localparam [31:0] GAIN_DEF_S1   = 32'h{default_word(1):08X};   // {DEFAULT_S1_DB:+d} dB",
        f"localparam [31:0] GAIN_DEF_S2   = 32'h{default_word(2):08X};   // {DEFAULT_S2_DB:+d} dB",
        f"localparam [31:0] GAIN_DEF_S3   = 32'h{default_word(3):08X};   // {DEFAULT_S3_DB:+d} dB",
        "function [31:0] gain_db_word;",
        "    input [7:0] db;",
        "    begin",
        "        case (db)",
    ]
    for b in range(256):
        db = b - 256 if b >= 128 else b
        lines.append(f"            8'h{b:02X}: gain_db_word = 32'h{db_word(db):08X};   // {db:+d} dB")
    lines += [
        "            default: gain_db_word = 32'h00000000;",
        "        endcase",
        "    end",
        "endfunction",
        "function [31:0] gain_raw_word;",
        "    input [7:0] raw;",
        "    begin",
        "        case (raw)",
    ]
    for b in range(256):
        lines.append(f"            8'h{b:02X}: gain_raw_word = 32'h{raw_word(b):08X};   // raw {b}")
    lines += [
        "            default: gain_raw_word = 32'h00000000;",
        "        endcase",
        "    end",
        "endfunction",
        "",
    ]
    return "\n".join(lines)


def write_vh(path: Path = ROM_VH) -> None:
    path.write_text(rom_text(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    write_vh()
    print(f"gain tables -> {ROM_VH}: 0 dB = {db_word(0):#010x}, -20 dB = {db_word(-20):#010x}, "
          f"raw 20 = {raw_word(20):#010x} ({20 * math.log10(gain_raw(20)):.1f} dB)")
