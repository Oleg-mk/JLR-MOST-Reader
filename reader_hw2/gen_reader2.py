#!/usr/bin/env python3
"""gen_reader2.py - the sheet of reader v2.0: the circuit of v1.0 plus two series resistors, for a board in a tube.

v2.0 is the same electronics on a board 26.5 mm wide inside a 30x30x1.5 aluminium tube (the
user's decision of 2026-10-05). The circuit is not drawn twice: this script loads
reader_hw/gen_reader.py, the source of v1.0's sheet, and writes its blocks 1-7 as they are into
this folder. What it changes describes the board, with one exception in the circuit (the last item):
  * the project name (most_reader_v2) and its own UUIDs, so the two projects never mix;
  * the title block (rev 2.0) and two lines of notes about the tube;
  * the Tang Nano footprint: only the header pins in TANG_PINS have pads, the seven that carry
    something and one at each corner they leave bare (pins 1..4 would sit over J4 on the other
    side); the strips are cut to them, and KiCad's parity check asks no pad of an unconnected pin;
    the HDMI overhang as the data sheet's photos show it
    (about 4 mm, not the 8 mm of v1.0's fab text), the USB-C's 2 mm, and a 3D body of the module
    so KiCad's 3D view shows the stack in the tube;
  * the FOT footprint's two action pins: rings of 2.1 mm, not 2.4, so that on the 26.5 mm board
    their copper keeps 0.3 mm from the long edges (their 1.8 mm holes sit 0.5 mm from them);
  * R43 (33 ohm) and R44 (68 ohm) in series right after U1 and U3: the lines they drive (RX_BUF,
    RX_IN) run about 40 and 60 mm on the two-layer board (added after the EMC review of 2026-10-06);
  * C45 8 mm across, 47u 63V (2026-10-10): the 10 mm one, pinned against J1's action pin, kept the
    module's header one pin further from J1 and the tube 2.54 mm longer.
v1.0's files are not touched: tools/check_sheet.py regenerates both sheets and compares them
with the committed ones.

    python reader_hw2/gen_reader2.py
"""
from __future__ import annotations

import importlib.util
import uuid as _uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
PROJECT = "most_reader_v2"
# the left header row (pads 1..20, pad 1 at the USB-C end) starts here: pads 1..4 sit over J4,
# which v2.0 carries on the other side under the module's USB-C end, and are left out of the
# header strip (they carry nothing: FPGA 73, 74, 75, 85)
TOP_ROW_FIRST = 5
# the header pins that go into the board (the user's choice, 2026-10-10): the seven that carry
# something (7 3V3_SW, 8 RX_IN, 21 5 V, 25 S/PDIF, the grounds 20, 22, 35) and one more at each corner
# they leave bare (5 at the USB-C end, where the cable pulls, 40 at the HDMI end); the strips are cut
# to these, and the rows of holes under the module are free for tracks
TANG_PINS = (5, 7, 8, 20, 21, 22, 25, 35, 40)
# C45 8 mm across (the user's choice, 2026-10-10): it sits against J1's action pin, and the 10 mm one's
# body covered the hole of the module's pad 20 one pin further towards J1; 63 V gives 47 uF in 8 x 10
C45_V2 = ("47u 63V", "Capacitor_SMD:CP_Elec_8x10")
# the module as the data sheet v1.3 shows it (p.3-4 photos, p.6 drawing): PCB 54.04 x 22.55,
# USB-C 2.0 mm and HDMI about 4 mm past its ends; soldered 2.5 mm above the board on the
# header plastic
TANG_USB_OVER, TANG_HDMI_OVER, TANG_LIFT, TANG_PCB = 2.0, 4.0, 2.5, 1.6


def load_v1():
    spec = importlib.util.spec_from_file_location("gen_reader", ROOT / "reader_hw" / "gen_reader.py")
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    return gen


def patch(gen, here: Path):
    """Point v1.0's generator at this folder and give it v2.0's title, notes and module footprint."""
    gen.HERE = here
    gen.PROJECT = PROJECT
    gen.NS = _uuid.UUID("5b1d3c6e-2f40-4a8b-9c7d-0e1f2a3b4c5d")     # v2.0's own UUIDs
    f, uid = gen.f, gen.uid

    def write(self, path: Path):
        self.junctions()
        libs = "\n".join(sym.text for sym in self.used.values())
        body = "\n".join(self.items)
        path.write_text(
            f'(kicad_sch (version 20231120) (generator "gen_reader") '
            f'(generator_version "10.0") (uuid "{uid("root")}") (paper "A3")\n'
            f'(title_block (title "JLR MOST Reader v2.0: the board in a tube") (date "2026-10-05") '
            f'(rev "2.0") (comment 1 "Generated by reader_hw2/gen_reader2.py from reader_hw/gen_reader.py: the circuit of v1.0 + R43, R44, C45 47u") '
            f'(comment 2 "MOST25 bypass, an FPGA listening, S/PDIF out on TOSLINK, one clock"))\n'
            f'(lib_symbols\n{libs}\n)\n{body}\n'
            f'(sheet_instances (path "/" (page "1")))\n)\n', encoding="utf-8")

    gen.Sheet.write = write
    v1_notes = gen.notes_block

    def notes_block(sh):
        v1_notes(sh)
        for i, line in enumerate((
                "v2.0: та сама схема на платі 26.5 мм у трубі 30x30x1.5. Зверху J1 і модуль (USB-C модуля в торцевій кришці),",
                "решта знизу, J6 і J4 теж: під кінцем модуля з USB-C. У гребінці модуля лише контакти 5, 7, 8, 20, 21, 22, 25, 35, 40: решта ні до чого не йдуть.")):
            sh.text(line, 17.78, 212.09 + 3.81 * (8 + i), 1.27)

    gen.notes_block = notes_block

    def tangnano_footprint():
        """The v1.0 footprint (pads, courtyards, outline) with the module's real overhangs on F.Fab,
        the left row's header model from TOP_ROW_FIRST and the module's body."""
        items = []
        for i in range(20):
            y = -24.13 + 2.54 * i
            for n, x in ((i + 1, -10.16), (i + 21, 10.16)):
                if n in TANG_PINS:
                    items.append(gen._fppad(str(n), "thru_hole", "circle", x, y, 1.7, 1.7, 1.0, f"tn{n}"))
        x0, x1, y0, y1 = -11.275, 11.275, -27.02, 27.02
        items.append(gen._fpbox(x0, y0, x1, y1, "F.Fab", 0.1, "tnfab"))
        items.append(gen._fpbox(-4.47, y0 - TANG_USB_OVER, 4.47, y0, "F.Fab", 0.1, "tnusbfab"))
        items.append(gen._fpbox(-7.5, y1, 7.5, y1 + TANG_HDMI_OVER, "F.Fab", 0.1, "tnhdmifab"))
        items.append(gen._fpbox(x0 - 0.11, y0 - 0.11, x1 + 0.11, y1 + 0.11, "F.SilkS", 0.12, "tnsilk"))
        ya = -24.13 + 2.54 * (TOP_ROW_FIRST - 1)
        items.append(gen._fpbox(-10.16 - 1.52, ya - 1.52, -10.16 + 1.52, 24.13 + 1.52, "F.CrtYd", 0.05, "tncrtl"))
        items.append(gen._fpbox(10.16 - 1.52, -24.13 - 1.52, 10.16 + 1.52, 24.13 + 1.52, "F.CrtYd", 0.05, "tncrtr"))
        items.append(gen._fptext(f"USB-C, +{TANG_USB_OVER:g} mm", 0, -25.6, "F.Fab", 0.8, "tnusb"))
        items.append(gen._fptext(f"HDMI, about +{TANG_HDMI_OVER:g} mm", 0, 25.6, "F.Fab", 0.8, "tnhdmi"))
        items.append(gen._fptext("pins " + " ".join(map(str, TANG_PINS)), -6.0, -21.5, "F.Fab", 0.6, "tnleft"))
        items.append(gen._fpdot(-11.9, -24.13, "tnpin1"))           # where pin 1 would be: the module's corner
        for first, x in ((1, -10.16), (21, 10.16)):          # the strips cut to runs of TANG_PINS
            runs = []
            for n in range(first, first + 20):
                if n in TANG_PINS:
                    if runs and runs[-1][-1] == n - 1:
                        runs[-1].append(n)
                    else:
                        runs.append([n])
            for run in runs:
                items.append(gen._fpmodel("Connector_PinHeader_2.54mm", f"PinHeader_1x{len(run):02d}_P2.54mm_Vertical",
                                          x, -24.13 + 2.54 * (run[0] - first)))
        items.append(gen._own_model(gen.FP_TANG))
        return gen._fp(gen.FP_TANG, "Sipeed Tang Nano 20K module, 54.04 x 22.55 mm, 2 x 20 pins on 2.54, rows 20.32 apart, "
                       "pad 1 = pin 73 (HSPI_DIN2) at the USB-C end; USB-C 2 mm and HDMI about 4 mm past the ends "
                       "(data sheet v1.3 p.3-6); soldered on pin headers 2.5 mm above the board, no sockets; in v2.0 "
                       "only pins " + ", ".join(map(str, TANG_PINS)) + " have pads: the seven that carry something "
                       "and one at each corner they leave bare; the header strips are cut to them",
                       "Sipeed Tang Nano 20K GW2AR", "through_hole", items, -29.0, 29.5)

    v1_fot = gen.te_fot_footprint

    def te_fot_footprint():
        text = v1_fot()
        old = "(size 2.4 2.4) (drill 1.8)"
        assert text.count(old) == 2, "the action pins' pads moved in gen_reader.py"
        return (text.replace(old, "(size 2.1 2.1) (drill 1.8)")
                .replace("holes (pad 0)", "holes (pad 0; rings of 2.1 mm in v2.0, 0.3 mm from the 26.5 mm board's edges)"))

    gen.NEW_FOOTPRINTS = ((gen.FP_FOT, te_fot_footprint), (gen.FP_T10, gen.toslink_t10_footprint),
                          (gen.FP_TANG, tangnano_footprint))

    # v2.0's one change to the circuit (2026-10-06, after the EMC review of the board): a series
    # resistor right after each buffer that drives a long line to the module - R43 between U1's
    # output and RX_BUF (~40 mm, three loads), R44 between U3's output and RX_IN (~60 mm to the FPGA's
    # oversampling input). On a two-layer board the lines are 100-130 ohm and the LVC edges ~1 ns.
    # R44 is 68 ohm: a model of RX_IN (the line, U3 at 15-25 ohm, the FPGA pin 6-8 pF) gives 13-31 %
    # overshoot with 33 ohm and at most 8 % with 68, the edge 1.0-1.6 ns, which the decoder does not
    # mind. R43 stays 33: RX_BUF also drives the ring's TX through R2, where a fast edge matters more.
    # tools/check_v2_circuit.py shorts them out and holds the rest to v1.0.
    v1_optics, v1_isolation = gen.optics_block, gen.isolation_block

    def same(a, b):
        return round(a[0], 3) == round(b[0], 3) and round(a[1], 3) == round(b[1], 3)

    def optics_block(sh):
        def wire(*pts):
            u1 = next((p for p in sh.parts if p.ref == "U1"), None)
            if u1 is not None and len(pts) == 2 and same(pts[0], u1.p("4")):
                r43 = sh.at_pin("R", "R43", "33", "1", (pts[0][0] + 2.54, pts[0][1]), r=90, fp=gen.SMD["R"])
                gen.Sheet.wire(sh, pts[0], r43.p("1"))
                gen.Sheet.wire(sh, r43.p("2"), pts[1])
            else:
                gen.Sheet.wire(sh, *pts)
        sh.wire = wire
        try:
            v1_optics(sh)
        finally:
            del sh.wire
        sh.text("R43: 33 Ом після U1 (v2.0), лінія RX_BUF 47 мм.", 17.78, 195.58, 1.27)

    def isolation_block(sh):
        def lbl(name, pin, length, side):
            if name == "RX_IN":
                r44 = sh.at_pin("R", "R44", "68", "1", (pin[0] + 2.54, pin[1]), r=90, fp=gen.SMD["R"])
                gen.Sheet.wire(sh, pin, r44.p("1"))
                gen.Sheet.lbl(sh, name, r44.p("2"), 2.54, side)
            else:
                gen.Sheet.lbl(sh, name, pin, length, side)
        sh.lbl = lbl
        try:
            v1_isolation(sh)
        finally:
            del sh.lbl
        sh.text("R44: 68 Ом після U3 (v2.0), лінія RX_IN ~60 мм.", 210.82, 195.58, 1.27)

    v1_add = gen.Sheet.add

    def add(self, key, ref, value, x, y, r=0, fp="", **kw):
        if ref == "C45":
            value, fp = C45_V2
        return v1_add(self, key, ref, value, x, y, r, fp, **kw)

    gen.Sheet.add = add
    gen.optics_block, gen.isolation_block = optics_block, isolation_block
    return gen


def tang_body(gen):
    """The module's envelope in the footprint's frame (origin between the rows, the USB-C towards
    -y), from the data sheet's drawing and photos: the PCB on the header plastic, the USB-C and the
    HDMI receptacles past its ends. The parts under the module (DC-DC, LDOs, crystals, the microSD
    slot) are not drawn: their heights are not published; check_fit.py keeps 2.0 mm for them."""
    z0, z1 = TANG_LIFT, TANG_LIFT + TANG_PCB
    green, metal = (0.05, 0.25, 0.12), (0.75, 0.75, 0.78)
    return [(green, gen._box(-11.275, 11.275, -27.02, 27.02, z0, z1)),
            (metal, gen._box(-4.47, 4.47, -27.02 - TANG_USB_OVER, -27.02 - TANG_USB_OVER + 7.35, z1, z1 + 3.26)),
            (metal, gen._box(-7.5, 7.5, 27.02 + TANG_HDMI_OVER - 11.5, 27.02 + TANG_HDMI_OVER, z1, z1 + 6.0)),
            (gen.BLACK, gen._box(-5.0, 5.0, -15.0, -5.0, z1, z1 + 0.9))]                  # the GW2AR, QN88


def main(here: Path = HERE):
    gen = patch(load_v1(), here)
    gen.main()
    (here / gen.MODELS / f"{gen.FP_TANG}.step").write_text(gen._step(gen.FP_TANG, tang_body(gen)), encoding="utf-8")
    print("wrote", f"{gen.MODELS}/{gen.FP_TANG}.step")


if __name__ == "__main__":
    main()
